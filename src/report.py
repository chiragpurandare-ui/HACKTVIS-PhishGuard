from pathlib import Path
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    PageBreak
)
from reportlab.lib.enums import TA_CENTER


BASE_DIR = Path(__file__).resolve().parent.parent
REPORT_DIR = BASE_DIR / "reports" / "generated"


def generate_report(scan_data):

    REPORT_DIR.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now()
    filename = f"phishguard_report_{timestamp.strftime('%Y%m%d_%H%M%S')}.pdf"

    report_path = REPORT_DIR / filename

    document = SimpleDocTemplate(
        str(report_path),
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        textColor=colors.HexColor("#087F8C"),
        fontSize=22,
        spaceAfter=8
    )

    heading_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#087F8C"),
        spaceBefore=14,
        spaceAfter=8
    )

    normal_style = styles["BodyText"]

    story = []

    # Header
    story.append(Paragraph("HACKTVIS PHISHGUARD", title_style))
    story.append(
        Paragraph("AI-Powered Phishing Detection Report", styles["Heading3"])
    )
    story.append(Spacer(1, 15))

    # Scan information
    story.append(Paragraph("1. Scan Information", heading_style))

    metadata = scan_data.get("metadata", {})

    scan_table = [
        ["Scan Date", timestamp.strftime("%d-%m-%Y %H:%M:%S")],
        ["Target URL", scan_data.get("url", "Not available")],
        ["Final URL", metadata.get("final_url", "Not available")],
        ["HTTP Status", str(metadata.get("status_code", "Unknown"))],
        ["Page Title", metadata.get("title", "Not available")]
    ]

    story.append(create_table(scan_table))
    story.append(Spacer(1, 10))

    # ML prediction
    story.append(Paragraph("2. Machine Learning Analysis", heading_style))

    phishing = scan_data.get("phishing_probability", 0) * 100
    legitimate = scan_data.get("legitimate_probability", 0) * 100

    ml_table = [
        ["Prediction", scan_data.get("verdict", "UNKNOWN")],
        ["Phishing Probability", f"{phishing:.2f}%"],
        ["Legitimate Probability", f"{legitimate:.2f}%"],
        ["Validation Status", "PROVISIONAL"]
    ]

    story.append(create_table(ml_table))

    story.append(Paragraph(
        "Note: Model probabilities are experimental outputs and should "
        "not be treated as confirmed security verdicts.",
        normal_style
    ))

    # Risk assessment
    story.append(Paragraph("3. Risk Assessment", heading_style))

    risk = scan_data.get("risk", {})

    risk_table = [
        ["Risk Score", f"{risk.get('score', 0)}/100"],
        ["Risk Level", risk.get("level", "UNKNOWN")]
    ]

    story.append(create_table(risk_table))

    # Risk indicators
    story.append(Paragraph("4. Detected Indicators", heading_style))

    reasons = risk.get("reasons", [])

    if reasons:
        for reason in reasons:
            story.append(Paragraph(f"• {reason}", normal_style))
            story.append(Spacer(1, 4))
    else:
        story.append(Paragraph(
            "No basic risk indicators were detected.",
            normal_style
        ))

    # Reputation
    story.append(Paragraph("5. Reputation Analysis", heading_style))

    reputation = scan_data.get("reputation", {})

    reputation_table = [
        ["Reputation Status", reputation.get("status", "UNKNOWN")],
        ["Indicator Score", str(reputation.get("risk_score", 0))],
        ["External Database", "NOT CONNECTED"]
    ]

    story.append(create_table(reputation_table))

    # Recommendations
    story.append(Paragraph("6. Security Recommendations", heading_style))

    recommendations = [
        "Verify the website domain before entering personal information.",
        "Avoid entering passwords or payment details on untrusted websites.",
        "Check the website address carefully for spelling differences.",
        "Use trusted security tools to verify suspicious websites.",
        "Treat automated predictions as indicators, not final proof."
    ]

    for recommendation in recommendations:
        story.append(Paragraph(f"• {recommendation}", normal_style))
        story.append(Spacer(1, 4))

    # Footer information
    story.append(Spacer(1, 20))
    story.append(Paragraph(
        "Generated by HACKTVIS PhishGuard",
        styles["Italic"]
    ))

    document.build(story)

    return str(report_path)


def create_table(data):

    table = Table(data, colWidths=[160, 330])

    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#E6F4F4")),
        ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor("#222222")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CCCCCC")),
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "TOP")
    ]))

    return table
